#!/usr/bin/env python3
"""Writes the C# belief parity test's fixture (C4.2, C4.10): a synthetic map, a script of the filter's
operations, and the beliefs this replay gets after each, with today's step (p0), P1 and P2. The
C# filter (BeliefGrid with HandMotion / DestinationMotion, MotionFeatures.Compute) must get the
same, to 1e-5. Rerun after changing kernels.py, features.py or their C# twins:

    python3 tools/belief/make_fixture.py
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import features as feat  # noqa: E402
import kernels  # noqa: E402
import synthetic  # noqa: E402

COLS, ROWS = 9, 7
OPEN = [not (r in (2, 4) and 2 <= c <= 6) for r in range(ROWS) for c in range(COLS)]      # two shelves
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Assets", "!_Project", "_Tests", "Editor", "BeliefParityFixture.g.cs")

# Each op: kind, then numbers. obs: channel(0 sight, 1 hearing, 3 testimony), x, z, sigma, conf, cell.
SCRIPT = [
    ("desire", [5, 40]), ("reset_prior",),
    ("obs", 0, 3.0, 2.0, 1.2, 0.8, -1), ("predict", 0.1, 4.0), ("predict", 0.1, 4.0),
    ("obs", 1, 10.5, 9.0, 2.0, 0.5, 30), ("predict", 0.1, 3.0),
    ("sweep", [0, 1, 2, 3], [0.6, 0.6, 0.3, 0.2]), ("predict", 0.1, 3.0),
    ("bias", 3, 0.05), ("predict", 0.1, 4.0),
    ("motion", "p1"), ("danger_from", 7.5, 7.5), ("predict", 0.1, 4.0), ("predict", 0.1, 4.0),
    ("motion", "p2"), ("places",), ("predict", 0.1, 4.0), ("predict", 0.1, 4.0), ("predict", 0.1, 4.0),
]
PLACES = [dict(kind="Job", cell=5, waited=10.0, x=0, z=0, answer_s=-1, habit=0), dict(kind="Clock", cell=40, waited=0.0, x=0, z=0, answer_s=-1, habit=0),
          dict(kind="Stay", cell=-1, waited=0.0, x=0, z=0, answer_s=-1, habit=0)]
FEATURES = dict(thought=[7.5, 7.5], seen=[3.0, 2.0], heading=[1.0, 0.0], time_left=0.5, open=True)


def run():
    m, d = synthetic.build(COLS, ROWS, OPEN)
    for p in PLACES:
        if p["cell"] >= 0:
            p["x"], p["z"] = float(m.x[p["cell"]]), float(m.z[p["cell"]])
    g = kernels.Grid(m)
    out = []
    for op in SCRIPT:
        k = op[0]
        if k == "desire":
            g.desire = m.distances(op[1])
        elif k == "reset_prior":
            g.reset_to_prior()
        elif k == "obs":
            ch = {0: "Sight", 1: "Hearing", 3: "Testimony"}[op[1]]
            g.apply(dict(ch=ch, x=op[2], z=op[3], sigma=op[4], conf=op[5], cell=op[6], outside=False))
        elif k == "predict":
            g.predict(op[1], op[2])
        elif k == "sweep":
            g.sweep(op[1], op[2])
        elif k == "bias":
            g.bias(op[1], op[2])
        elif k == "motion":
            g.motion = kernels.HandMotion(feat.HAND["p1"]) if op[1] == "p1" else kernels.DestinationMotion()
        elif k == "danger_from":
            g.danger = feat.danger(m, [op[1], op[2]], feat.HAND)
        elif k == "places":
            rate, exit_rate, _, _ = feat.compute(m, dict(FEATURES, places=PLACES), feat.HAND)
            g.motion.rate, g.motion.exit_rate = rate, exit_rate
        out.append(g.b.copy())
    return m, out


def cs_floats(a):
    return "new float[] { " + ", ".join(repr(float(np.float32(x))) + "f" for x in np.asarray(a).reshape(-1)) + " }"


def main():
    m, out = run()
    lines = ["// <auto-generated> by tools/belief/make_fixture.py: the Python replay's beliefs on a synthetic map. Do not edit.",
             "public static class BeliefParityFixture", "{",
             f"    public const int Columns = {COLS}, Rows = {ROWS};",
             "    public static readonly bool[] Open = { " + ", ".join("true" if o else "false" for o in OPEN) + " };",
             f"    public const int Steps = {len(out)};",
             "    public static readonly float[] Expected = " + cs_floats(np.stack(out)) + ";", "}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.abspath(OUT)}: {m.n} cells, {len(out)} steps")


if __name__ == "__main__":
    main()
