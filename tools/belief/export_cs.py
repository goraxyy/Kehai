"""Write the trained motion models into the game as generated C# (MotionWeights.g.cs).

    python export_cs.py --weights out/weights.npz          the trained models
    python export_cs.py --untrained                        starting weights (before any training)

The file holds m1's gains, m2–m4's weights as flat float arrays in LearnedMotion's order, a
model card (data, seeds, profiles, commit, validation scores) and the parity fixture: what
each PyTorch kernel makes of a fixed belief on the synthetic map (make_fixture.py). The
EditMode test MotionModelTests.LearnedKernels_MatchPyTorch holds the C# kernels to it.
weights.npz is never committed (the repo holds code only); the generated .cs is.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import textwrap
from pathlib import Path

import numpy as np
import torch

import kernels
from make_fixture import COLUMNS, DT, OPEN, ROWS, SPEED, fixture_from, fixture_outputs, synthetic_map

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
TARGET = REPO / "Assets/!_Project/_Game/AI/Scripts/Belief/MotionWeights.g.cs"


def f32(v: float) -> str:
    v = float(np.float32(v))
    if v == 0:
        return "0f"
    s = f"{v:.9g}"
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def array(name: str, values, per_line: int = 8, kind: str = "float") -> str:
    values = list(values)
    if kind == "bool":
        items = ["true" if v else "false" for v in values]
    else:
        items = [f32(v) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    body = ",\n            ".join(lines)
    return f"        static readonly {kind}[] {name} =\n        {{\n            {body}\n        }};\n"


def models_from(weights: dict) -> dict:
    models = {"m0": kernels.make("m0"), "m1": kernels.HandKernel(avoid=True, gains=weights.get("m1"))}
    for mid in ("m2", "m3", "m4"):
        m = kernels.LearnedKernel(mid)
        if mid in weights:
            m.load_pack(weights[mid])
        models[mid] = m
    return models


def untrained(seed: int = 7) -> dict:
    """Starting weights. The MLP's last layer gets small random values (not the zeros training
    starts from) so the parity fixture exercises every weight."""
    torch.manual_seed(seed)
    out = {"m1": dict(kernels.SHIPPED)}
    for mid in ("m2", "m3", "m4"):
        m = kernels.LearnedKernel(mid)
        if mid != "m2":
            with torch.no_grad():
                m.w3.normal_(0, 0.05)
                m.b3.normal_(0, 0.05)
        out[mid] = m.pack()
    return out


def commit() -> str:
    try:
        return subprocess.check_output(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        return "unknown"


def write(weights: dict, card: dict, trained: bool, best: str, out: Path) -> None:
    models = models_from(weights)
    fixture = fixture_outputs(models)
    m = synthetic_map()
    g = models["m1"].gains_float()

    card_lines = [f"{k}: {v}" for k, v in card.items()]
    card_text = "\n".join("//   " + line for line in card_lines)
    card_str = "\\n".join(line.replace("\\", "\\\\").replace('"', '\\"') for line in card_lines)

    parts = []
    parts.append(textwrap.dedent(f"""\
        // <auto-generated>
        //   Written by tools/belief/export_cs.py — do not edit by hand; re-run the exporter.
        // </auto-generated>
        //
        // The learned motion models for Karen's belief grid (Belief/LearnedMotion.cs), and m1's
        // tuned gains (Belief/MotionModel.cs). How they were made: tools/belief/README.md.
        //
        // Model card
        @CARD@

        namespace Kehai.Karen
        {{
            public static class MotionWeights
            {{
                public static readonly bool Trained = {"true" if trained else "false"};
                public const string Best = "{best}";   // the learned model chosen on validation (playtest shadows run it)
                public const string Card = "{card_str}";

                public static HandMotion.Gains M1Gains => new HandMotion.Gains
                {{
                    MovingProbability = {f32(g["moving"])}, DesireGain = {f32(g["desire"])}, HabitGain = {f32(g["habit"])},
                    DangerAvoidance = {f32(g["avoid"])}, Uncertainty = {f32(g["leak"])}, SpeedScale = {f32(g["speed_scale"])},
                    DangerRadius = {f32(g["radius"])}, TrailWeight = {f32(g["trail"])}
                }};

                public static float[] Pack(LearnedMotion.Kind kind)
                {{
                    switch (kind)
                    {{
                        case LearnedMotion.Kind.LogLinear: return M2;
                        case LearnedMotion.Kind.Mlp: return M3;
                        default: return M4;
                    }}
                }}

        """).replace("@CARD@", card_text))
    for mid in ("m2", "m3", "m4"):
        parts.append(array(mid.upper(), models[mid].pack()))
        parts.append("\n")
    parts.append(textwrap.indent(textwrap.dedent(f"""\
        // ---- the parity fixture (tools/belief/make_fixture.py) ----
        // A {COLUMNS} × {ROWS} synthetic map ({m.n} cells), MotionFeatures.FillSynthetic's features, a fixed
        // belief (FixtureFrom), one kernel step of dt = {float(DT)} s at speed {float(SPEED)}: what PyTorch made of it.
        public const int FixtureColumns = {COLUMNS}, FixtureRows = {ROWS};
        public const float FixtureDt = {f32(DT)}, FixtureSpeed = {f32(SPEED)};
        public static bool[] FixtureOpenCells => FixtureOpen;
        public static float[] FixtureFromCells => FixtureFrom1;
        public static float[] FixtureFromHeadings => FixtureFrom9;
        public static float[] FixtureExpected(string id)
        {{
            switch (id)
            {{
                case "m0": return FixtureM0;
                case "m1": return FixtureM1;
                case "m2": return FixtureM2;
                case "m3": return FixtureM3;
                default: return FixtureM4;
            }}
        }}

        """), "        "))
    parts.append(array("FixtureOpen", OPEN, per_line=COLUMNS, kind="bool"))
    parts.append(array("FixtureFrom1", fixture_from(m.n)))
    parts.append(array("FixtureFrom9", fixture_from(m.n * kernels.HEADINGS)))
    for mid in ("m0", "m1", "m2", "m3", "m4"):
        parts.append(array("Fixture" + mid.upper(), fixture[mid]))
    parts.append("    }\n}\n")
    out.write_text("".join(parts))
    print(f"wrote {out} ({out.stat().st_size // 1024} KB): trained={trained}, best={best}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--weights", help="weights.npz from train.py")
    ap.add_argument("--untrained", action="store_true")
    ap.add_argument("--out", default=str(TARGET))
    a = ap.parse_args()
    if a.untrained:
        weights = untrained()
        card = {"status": "untrained: the starting weights, before any training (tools/belief/README.md)",
                "commit": commit()}
        write(weights, card, False, "m0", Path(a.out))
        return
    z = np.load(a.weights, allow_pickle=False)
    weights = {k: z[k] for k in ("m2", "m3", "m4") if k in z.files}
    weights["m1"] = dict(zip(kernels.M1_ORDER, [float(v) for v in z["m1"]]))
    card = json.loads(str(z["card"])) if "card" in z.files else {}
    card.setdefault("commit", commit())
    best = str(z["best"]) if "best" in z.files else "m0"
    write(weights, card, True, best, Path(a.out))


if __name__ == "__main__":
    main()
