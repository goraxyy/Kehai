#!/usr/bin/env python3
"""Writes the cross-language pack test's fixture (C3.7): a pack signed by pack.py with a key made
here and thrown away; only its public half and the signed pack go into the test file. The
game's ModelPack must accept it, and refuse it once a byte of the body changes.

    python3 tools/learn/make_pack_fixture.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pack  # noqa: E402
import rsa_sign  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Assets", "!_Project", "_Tests", "Editor", "PackFixture.g.cs")


def main():
    key = rsa_sign.generate(2048)
    part = {"kind": "start", "name": "LedgerStart", "card": {"version": "fixture", "trained": False},
            "sprint_share": 0.25, "tricks": {}, "kinds": {"sight": [0.11]}, "answers": {"fog_reset": 33.0}, "hides": [["Stockroom", 0.4]]}
    text = pack.build([part], 5, key, created="2026-11-11T00:00:00+00:00")
    esc = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    with open(OUT, "w") as f:
        f.write("// <auto-generated> by tools/learn/make_pack_fixture.py: a pack signed in Python with a key made\n"
                "// and thrown away; only its public half is kept. Do not edit.\n"
                "public static class PackFixture\n{\n"
                f'    public const string Modulus = "{rsa_sign.b64int(key["n"])}";\n'
                f'    public const string Exponent = "{rsa_sign.b64int(key["e"])}";\n'
                f'    public const string Pack = "{esc}";\n'
                "}\n")
    print("wrote " + os.path.abspath(OUT))


if __name__ == "__main__":
    main()
