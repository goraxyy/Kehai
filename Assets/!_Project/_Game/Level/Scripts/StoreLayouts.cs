    public sealed class Layout
    {
        public readonly string Id, Name;
        public readonly bool HeldOut;
        readonly string[] rows;
        public int Height => rows.Length;
        public int Width => rows[0].Length;
        public char At(int row, int column) => row < 0 || row >= Height || column < 0 || column >= Width ? '.' : rows[row][column];
        public bool Shelf(int row, int column) => row > 0 && row < Height - 1 && column > 0 && column < Width - 1 && (At(row,column) == '#' || At(row,column) == '+' || At(row,column) == '|');
        internal Layout(string id, string name, bool heldOut, params string[] rows)
        {
            Id = id; Name = name; HeldOut = heldOut; this.rows = rows;
            if (rows.Length != 24) throw new ArgumentException("Layout must have 24 rows");
            foreach (string row in rows) if (row.Length != 26) throw new ArgumentException("Layout must have 26 columns");
        }
        public Vector3 Position(int row, int column) => new Vector3(25f + (column - .5f) * Pitch, 0f, -120f - (row - .5f) * Pitch);
        public string SectionAt(int row, int column) => StoreLayout.SignAt(Position(row,column));
    }
