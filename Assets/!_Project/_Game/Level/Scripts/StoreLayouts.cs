    public static Layout Find(string id)
    {
        foreach (var layout in All) if (string.Equals(layout.Id, id, StringComparison.OrdinalIgnoreCase)) return layout;
        throw new ArgumentException("Unknown store layout: " + id);
    }
    public static string ForShift(int shift) => shift < 3 ? "today" : shift == 3 ? "labyrinth" : "brick-bond";
    public static string ForTraining(int seed, int shift)
    {
        // Fixed pool: a held-out name cannot enter training through shuffled array indices.
        string[] pool = { "today", "racetrack", "labyrinth", "fishbone", "brick-bond" };
        if (shift < 3) return "today";
        return pool[(int)((uint)(seed * 397 ^ shift * 7919) % (uint)pool.Length)];
    }
